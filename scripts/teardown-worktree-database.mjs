#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { lstat, readFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

import {
  createWorktreeDatabaseConfig,
  GENERATED_ENV_MARKER,
} from "./setup-worktree-database.mjs";

const POSTGRES_USER = "calvinist_parrot";
const POSTGRES_CONTAINER = "calvinist-parrot-postgres";

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd,
    encoding: "utf8",
    input: options.input,
    stdio: options.input
      ? ["pipe", "inherit", "inherit"]
      : ["ignore", "inherit", "inherit"],
  });

  if (result.error) {
    throw result.error;
  }

  if (result.status !== 0) {
    throw new Error(
      `${command} ${args.join(" ")} exited with status ${result.status}`,
    );
  }
}

export function parseTeardownArgs(args) {
  if (args.length === 1 && args[0] === "--dry-run") {
    return { dryRun: true, confirmation: null };
  }

  if (args.length === 2 && args[0] === "--confirm" && args[1]) {
    return { dryRun: false, confirmation: args[1] };
  }

  throw new Error(
    "Usage: npm run db:worktree:teardown -- --dry-run OR npm run db:worktree:teardown -- --confirm <worktree-id>",
  );
}

export function renderDropDatabaseSql() {
  return `
SELECT pg_advisory_lock(hashtext(:'db_name'));

SELECT pg_terminate_backend(pid)
FROM pg_stat_activity
WHERE datname = :'db_name'
  AND pid <> pg_backend_pid();

SELECT format('DROP DATABASE %I', :'db_name')
WHERE EXISTS (
  SELECT 1 FROM pg_database WHERE datname = :'db_name'
)
\\gexec

SELECT pg_advisory_unlock(hashtext(:'db_name'));
`;
}

export function assertCurrentWorktreePath(worktreePath, currentDirectory) {
  const resolvedPath = path.resolve(worktreePath);
  const resolvedCurrentDirectory = path.resolve(currentDirectory);

  if (resolvedPath !== resolvedCurrentDirectory) {
    throw new Error(
      `Refusing teardown because CODEX_WORKTREE_PATH (${resolvedPath}) does not match the current directory (${resolvedCurrentDirectory}).`,
    );
  }
}

export async function inspectWorktreeDatabaseTarget(worktreePath) {
  const resolvedPath = path.resolve(worktreePath);
  const gitPath = path.join(resolvedPath, ".git");
  const envPath = path.join(resolvedPath, ".env");
  const config = createWorktreeDatabaseConfig(resolvedPath);

  const gitStats = await lstat(gitPath);
  if (!gitStats.isFile()) {
    throw new Error(
      `Refusing teardown because ${resolvedPath} is not a linked Git worktree.`,
    );
  }

  const envContents = await readFile(envPath, "utf8");
  if (!envContents.startsWith(GENERATED_ENV_MARKER)) {
    throw new Error(
      `Refusing teardown because ${envPath} was not generated by the worktree database setup.`,
    );
  }

  for (const databaseName of Object.values(config.databaseNames)) {
    if (!envContents.includes(`/${databaseName}?schema=public`)) {
      throw new Error(
        `Refusing teardown because ${envPath} does not target ${databaseName}.`,
      );
    }
  }

  return config;
}

function printTarget(config, action) {
  console.log(`${action} isolated databases for worktree ${config.worktreeId}:`);
  console.log(`- development: ${config.databaseNames.development}`);
  console.log(`- shadow: ${config.databaseNames.shadow}`);
  console.log(`- test: ${config.databaseNames.test}`);
}

export async function teardownWorktreeDatabases(
  worktreePath,
  confirmation,
  options = {},
) {
  const resolvedPath = path.resolve(worktreePath);
  const config = await inspectWorktreeDatabaseTarget(resolvedPath);

  assertCurrentWorktreePath(
    resolvedPath,
    options.currentDirectory ?? process.cwd(),
  );

  if (confirmation !== config.worktreeId) {
    throw new Error(
      `Confirmation mismatch. Rerun with --confirm ${config.worktreeId} after reviewing the dry-run output.`,
    );
  }

  const runCommand = options.runCommand ?? run;
  runCommand(
    "docker",
    ["start", POSTGRES_CONTAINER],
    { cwd: resolvedPath },
  );

  for (const databaseName of Object.values(config.databaseNames)) {
    runCommand(
      "docker",
      [
        "exec",
        "-i",
        POSTGRES_CONTAINER,
        "psql",
        "--no-psqlrc",
        `--username=${POSTGRES_USER}`,
        "--dbname=postgres",
        "--set=ON_ERROR_STOP=1",
        `--set=db_name=${databaseName}`,
      ],
      { cwd: resolvedPath, input: renderDropDatabaseSql() },
    );
  }

  printTarget(config, "Removed");
  return config;
}

async function main() {
  const worktreePath = process.env.CODEX_WORKTREE_PATH;
  if (!worktreePath) {
    throw new Error(
      "CODEX_WORKTREE_PATH is required. Run this command from the Codex worktree being removed.",
    );
  }

  const { dryRun, confirmation } = parseTeardownArgs(process.argv.slice(2));
  const resolvedPath = path.resolve(worktreePath);
  assertCurrentWorktreePath(resolvedPath, process.cwd());
  const config = await inspectWorktreeDatabaseTarget(resolvedPath);

  if (dryRun) {
    printTarget(config, "Would remove");
    console.log(
      `No databases were changed. To proceed, rerun with --confirm ${config.worktreeId}.`,
    );
    return;
  }

  await teardownWorktreeDatabases(resolvedPath, confirmation);
}

const executedModuleUrl = process.argv[1]
  ? pathToFileURL(path.resolve(process.argv[1])).href
  : "";

if (import.meta.url === executedModuleUrl) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
